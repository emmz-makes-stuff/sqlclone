			SET @STRSQL = 'SELECT SEQ_ID, ' + @ATTRIBUTE_SYSTEM_NAME + ' AS DATA_VALUE FROM [SRM-CustomEntities_511].DBO.[CUS_ENTITY_DATA] WITH (NOLOCK) WHERE SRM_CLIENTS_SEQ_ID = ' + CAST(@SRM_CLIENTS_SEQ_ID AS nvarchar) + ' AND SRM_CLIENT_ENTITIES_SEQ_ID = ' + CAST(@SRM_CLIENT_ENTITIES_SEQ_ID AS nvarchar) + ' AND SEQ_ID = ' + CAST(@CUS_ENTITY_DATA_SEQ_ID AS nvarchar)
