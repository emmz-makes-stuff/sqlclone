			SELECT @SRM_CLIENT_ENTITIES_SEQ_ID,SEQ_ID,@SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID,DATA_VALUE,NULL,NULL,NULL,@SRM_CLIENTS_SEQ_ID FROM @DATA_TABLE
		END
		ELSE IF @DATA_TYPE_ID IN (6, 7, 8) --STRING
		BEGIN
			INSERT INTO [SRM-CustomEntities_511].DBO.[CUS_PIVOT_NON_UNIQUE_INDEXES] 
				(SRM_CLIENT_ENTITIES_SEQ_ID, 
										CUS_ENTITY_DATA_SEQ_ID, 
										SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID, 
										ATTRIBUTE_DATETIME, 
										ATTRIBUTE_DECIMAL, 
										ATTRIBUTE_STRING, 
										ATTRIBUTE_BOOLEAN, 
										SRM_CLIENTS_SEQ_ID)
			SELECT @SRM_CLIENT_ENTITIES_SEQ_ID,SEQ_ID,@SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID,NULL,NULL, DATA_VALUE ,NULL,@SRM_CLIENTS_SEQ_ID FROM @DATA_TABLE
		END
		FETCH NEXT FROM CUR_ATTRIBUTES INTO @SRM_CLIENT_ENTITIES_SEQ_ID, @SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID, @ATTRIBUTE_SYSTEM_NAME, @DATA_TYPE_ID
	END

	CLOSE CUR_ATTRIBUTES 
	DEALLOCATE CUR_ATTRIBUTES 

	SET @ERROR = 0
	SET @ERROR_DESCRIPTION = ''

	--PRINT 'END POPULATE PIVOT _____________________________'
END












