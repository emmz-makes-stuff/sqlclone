		END
		ELSE IF @DATA_TYPE_ID IN (2) --BOOLEAN
		BEGIN 
			UPDATE @DATA_TABLE SET DATA_VALUE = 'N' WHERE DATA_VALUE = 'FALSE'
			UPDATE @DATA_TABLE SET DATA_VALUE = 'Y' WHERE DATA_VALUE = 'TRUE'
