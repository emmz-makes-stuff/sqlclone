			SELECT @SRM_CLIENT_ENTITIES_SEQ_ID,SEQ_ID,@SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID, NULL,NULL,NULL, DATA_VALUE, @SRM_CLIENTS_SEQ_ID FROM @DATA_TABLE
		END
		ELSE IF @DATA_TYPE_ID IN (4, 5 ) --DATETIME
		BEGIN
			SELECT @DATA_VALUE = SEQ_ID FROM @DATA_TABLE
			INSERT INTO [SRM-CustomEntities_511].DBO.[CUS_PIVOT_NON_UNIQUE_INDEXES] 
				(SRM_CLIENT_ENTITIES_SEQ_ID, 
										CUS_ENTITY_DATA_SEQ_ID, 
										SRM_CLIENT_ENTITY_ATTRIBUTES_SEQ_ID, 
